"""
text_utils — очистка текста для озвучки.
Владельцы: EMOJI_PATTERN, HUM_STRIP, clean_for_speech.
Зависимости: только re.
"""
import re

# ============================================
# ОЧИСТКА ТЕКСТА ДЛЯ ОЗВУЧКИ
# ============================================
EMOJI_PATTERN = re.compile(
    "["
    "\U0001F000-\U0001F0FF"
    "\U0001F100-\U0001F1FF"
    "\U0001F200-\U0001F2FF"
    "\U0001F300-\U0001F5FF"
    "\U0001F600-\U0001F64F"
    "\U0001F680-\U0001F6FF"
    "\U0001F700-\U0001F77F"
    "\U0001F780-\U0001F7FF"
    "\U0001F800-\U0001F8FF"
    "\U0001F900-\U0001F9FF"
    "\U0001FA00-\U0001FA6F"
    "\U0001FA70-\U0001FAFF"
    "\U00002190-\U000021FF"
    "\U00002300-\U000023FF"
    "\U000024C2-\U000024C2"
    "\U00002600-\U000026FF"
    "\U00002700-\U000027BF"
    "\U00002B00-\U00002BFF"
    "\U0000FE00-\U0000FE0F"
    "\U0000200D-\U0000200D"
    "\U000020E3-\U000020E3"
    "]+", flags=re.UNICODE)
# отдельные "ммм/мм/м-м-м" вырезаются из аудио совсем
HUM_STRIP = re.compile(
    r"(?<![а-яА-яёЁa-zA-Z0-9])"
    r"(?:[мМ]{2,}\.{0,3}|[мМ](?:[-–—][мМ])+)"
    r"(?![а-яА-яёЁa-zA-Z0-9])")

def clean_for_speech(text):
    t = EMOJI_PATTERN.sub("", text)
    t = t.replace("~", "")
    t = HUM_STRIP.sub("", t)
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"^[,.:;!\s]+", "", t)
    return t
